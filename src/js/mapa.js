'use strict';

let dados = document.querySelectorAll('.dado');

function esconderDado() {
    dados.forEach((dado) => {
        dado.style.display = 'none';
    });
}

let dado_saotome = document.getElementById('dado_saotome');
document.getElementById('saotome').addEventListener('click', function() {
    esconderDado();
    dado_saotome.style.display = 'block';
});

